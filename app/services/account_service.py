from datetime import datetime, timezone
from decimal import Decimal
from uuid import UUID, uuid4
import asyncpg
from app.core.exceptions import AccountNotFoundError
from app.models.account import Account
from app.schemas.account import AccountCreate, AccountResponse, BalanceResponse


class AccountService:
    """Business logic and processing for accounts."""

    def __init__(self, conn: asyncpg.Connection):
        self.conn = conn

    async def create_account(self, account_in: AccountCreate) -> AccountResponse:
        """
        Create a new account in PostgreSQL.
        - The name is already validated and stripped by the AccountCreate schema.
        - Initial balance is strictly zero (clients cannot set this).
        - Unique UUID ID is generated by the system.
        """
        account_id = uuid4()
        balance = Decimal("0.0000")
        created_at = datetime.now(timezone.utc)

        query = """
            INSERT INTO accounts (id, name, balance, created_at)
            VALUES ($1, $2, $3, $4)
            RETURNING id, name, balance, created_at;
        """
        row = await self.conn.fetchrow(query, account_id, account_in.name, balance, created_at)
        account = Account(
            id=row["id"],
            name=row["name"],
            balance=row["balance"],
            created_at=row["created_at"],
        )
        return AccountResponse.model_validate(account)

    async def get_account_by_id(self, account_id: UUID) -> AccountResponse | None:
        """Retrieve an account by ID."""
        query = """
            SELECT id, name, balance, created_at
            FROM accounts
            WHERE id = $1;
        """
        row = await self.conn.fetchrow(query, account_id)
        if not row:
            return None
        account = Account(
            id=row["id"],
            name=row["name"],
            balance=row["balance"],
            created_at=row["created_at"],
        )
        return AccountResponse.model_validate(account)

    async def get_balance(self, account_id: UUID) -> BalanceResponse:
        """Return the current balance of an account, or raise AccountNotFoundError."""
        balance = await self.conn.fetchval(
            "SELECT balance FROM accounts WHERE id = $1;", account_id
        )
        if balance is None:
            raise AccountNotFoundError(f"Account {account_id} not found")
        return BalanceResponse(account_id=account_id, balance=balance)
